
const mongoose = require("mongoose");

const sharedGroupSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      trim: true,
      maxlength: 80,
    },
    description: {
      type: String,
      default: "",
      trim: true,
    },
    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    members: [
      {
        type: mongoose.Schema.Types.ObjectId,
        ref: "User",
        required: true,
      },
    ],
  },
  { timestamps: true }
);

sharedGroupSchema.index({ members: 1, createdAt: -1 });

module.exports =
  mongoose.models.SharedGroup ||
  mongoose.model("SharedGroup", sharedGroupSchema);
